export function writeDart(model: TokenModel): WriteResult {
  const notes = new Set<string>(model.notes)
  const byKey = new Map(model.tokens.map((t) => [t.key, t]))
  const pick = (kind: ModelToken["kind"], layer?: ModelToken["layer"]) =>
    model.tokens.filter((t) => t.kind === kind && (!layer || t.layer === layer))

  const semanticColors = pick("color", "semantic")
  const colorGroups = COLOR_GROUPS.map((group) => ({
    group,
    tokens: semanticColors.filter((t) => colorGroupFor(t) === group),
  })).filter((g) => g.tokens.length > 0)

  const entriesFor = (tokens: ModelToken[]) =>
    tokens.map((t) => ({ member: dartMember(t.key), expr: expressionFor(t, "", "dark", byKey, notes) }))
  const densityImports = ["import 'dart:ui';", "", `import '${relativeImport("semantics/density/", "core/density.gen.dart")}';`]

  const standards: Array<ThemeField & { file: GeneratedFile }> = [
    {
      field: "radius",
      className: RADIUS_CLASS,
      import: "density/radius.gen.dart",
      file: standardFile("semantics/density/", "radius.gen.dart", RADIUS_CLASS, "Semantic radius sizes, in logical pixels.", "double", densityImports, entriesFor(pick("radius", "semantic"))),
    },
    {
      field: "spacing",
      className: SPACING_CLASS,
      import: "density/spacing.gen.dart",
      file: standardFile("semantics/density/", "spacing.gen.dart", SPACING_CLASS, "Semantic spacing sizes, in logical pixels.", "double", densityImports, entriesFor(pick("spacing", "semantic"))),
    },
    {
      // Sizes have no core/semantic split in Strata, so every size token gets
      // a semantic member; core ones are referenced, semantic ones resolved.
      field: "size",
      className: SIZE_CLASS,
      import: "density/size.gen.dart",
      file: standardFile("semantics/density/", "size.gen.dart", SIZE_CLASS, "Component sizes (button and field heights), in logical pixels.", "double", densityImports, entriesFor(pick("size"))),
    },
    {
      field: "typography",
      className: TYPOGRAPHY_CLASS,
      import: "typography.gen.dart",
      file: standardFile(
        "semantics/",
        "typography.gen.dart",
        TYPOGRAPHY_CLASS,
        "Semantic text styles. Weight drives the Geist variable font's `wght` axis.",
        "TextStyle",
        ["import 'package:flutter/painting.dart';", "", `import '${relativeImport("semantics/", "core/typography.gen.dart")}';`],
        pick("typography").map((t) => ({ member: dartMember(t.key), expr: typeStyleExpression(t.typeStyle!) })),
      ),
    },
    {
      field: "motion",
      className: MOTION_CLASS,
      import: "motion.gen.dart",
      file: standardFile(
        "semantics/",
        "motion.gen.dart",
        MOTION_CLASS,
        "Motion: durations and easing. Pick a duration by the size of the change.",
        "Duration",
        ["import 'package:flutter/animation.dart';", "", `import '${relativeImport("semantics/", "core/motion.gen.dart")}';`],
        [
          ...entriesFor(pick("duration")).map((e) => ({ ...e, type: "Duration" as DartType })),
          ...entriesFor(pick("easing")).map((e) => ({ ...e, type: "Curve" as DartType })),
        ],
        [
          "",
          "  /// The same set with every duration zero, for reduced motion. Curves",
          "  /// stay so a caller can still read them. `StrataMotion.of` picks it.",
          `  ${MOTION_CLASS} get reduced => ${MOTION_CLASS}(`,
          ...pick("duration").map((t) => `        ${dartMember(t.key)}: Duration.zero,`),
          ...pick("easing").map((t) => `        ${dartMember(t.key)}: ${dartMember(t.key)},`),
          "      );",
        ],
      ),
    },
  ]
  const gradients = pick("gradient")
  const fields: ThemeField[] = [
    ...colorGroups.map(({ group }) => ({ field: group.field, className: group.className, import: "" })),
    ...(gradients.length > 0 ? [{ field: "gradient", className: GRADIENT_CLASS, import: "" }] : []),
    ...standards.map(({ field, className, import: imp }) => ({ field, className, import: imp })),
  ]

  const files: GeneratedFile[] = [
    coreFile(CORE_COLOR_CLASS, "color.gen.dart", "Core colour ramps. The only colour literals in Strata.", pick("color", "core")),
    coreFile(
      CORE_DENSITY_CLASS,
      "density.gen.dart",
      "Core radius, spacing, and size scales, in logical pixels.",
      [...pick("radius", "core"), ...pick("spacing", "core"), ...pick("size", "core")],
    ),
    coreFile(CORE_TYPOGRAPHY_CLASS, "typography.gen.dart", "Core typescale primitives. Tracking is in em; line height is a ratio.", pick("typescale", "core")),
    coreFile(CORE_MOTION_CLASS, "motion.gen.dart", "Core durations and easing curves. Easing follows web's CSS keywords.", [...pick("duration", "core"), ...pick("easing", "core")]),
    ...standards.map((s) => s.file),
    themeFile(
      colorGroups.map(({ group, tokens }) => ({ group, members: tokens.map((t) => dartMember(t.key)) })),
      gradients,
      fields,
    ),
    ...model.brands.map((brand) => brandFile(brand, colorGroups, gradients, standards, byKey, notes)),
    brandEnumFile(model.brands),
    barrelFile(model.brands),
    manifestFile(model),
  ]

  checkMemberCollisions(model.tokens, notes)
  return { files, notes: [...notes].sort() }
}

function barrelFile(brands: string[]): GeneratedFile {
  const exports = [
    "core/color.gen.dart",
    "core/density.gen.dart",
    "core/motion.gen.dart",
    "core/typography.gen.dart",
    "semantics/density/radius.gen.dart",
    "semantics/density/size.gen.dart",
    "semantics/density/spacing.gen.dart",
    "semantics/motion.gen.dart",
    "semantics/theme.gen.dart",
    "semantics/themes/brands.gen.dart",
    ...brands.map((b) => `semantics/themes/brands/${b}.gen.dart`),
    "semantics/typography.gen.dart",
  ]
  return file("", "tokens.gen.dart", exports.map((e) => `export '${e}';`).join("\n"))
}

function symbolFor(token: ModelToken): string {
  if (token.layer === "core") return coreRef(token)
  const cls: Partial<Record<ModelToken["kind"], string>> = {
    radius: RADIUS_CLASS,
    spacing: SPACING_CLASS,
    size: SIZE_CLASS,
    typography: TYPOGRAPHY_CLASS,
    duration: MOTION_CLASS,
    easing: MOTION_CLASS,
    gradient: GRADIENT_CLASS,
  }
  return `${cls[token.kind] ?? colorGroupFor(token).className}.${dartMember(token.key)}`
}

function manifestFile(model: TokenModel): GeneratedFile {
  const manifest = {
    brands: model.brands,
    modes: MODES,
    tokens: model.tokens.map((t) => ({
      key: t.key,
      dart: symbolFor(t),
      sourceId: t.sourceId,
      layer: t.layer,
      kind: t.kind,
      collection: t.collection,
    })),
  }
  return { path: "", name: "manifest.gen.json", content: `${JSON.stringify(manifest, null, 2)}\n` }
}

/** Two keys that shorten to the same member in one class would not compile. */
function checkMemberCollisions(tokens: ModelToken[], notes: Set<string>): void {
  const seen = new Map<string, string>()
  for (const t of tokens) {
    const symbol = symbolFor(t)
    const prev = seen.get(symbol)
    if (prev && prev !== t.key) {
      throw new Error(`Dart member collision: ${prev} and ${t.key} both map to ${symbol}`)
    }
    seen.set(symbol, t.key)
  }
  if (seen.size === 0) notes.add("model has no tokens")
}
