export interface GeneratedFile {
  /** Directory relative to `lib/src/tokens/`, with a trailing slash. */
  path: string
  name: string
  content: string
}

export interface WriteResult {
  files: GeneratedFile[]
  notes: string[]
}

const HEADER = [
  "// GENERATED by tools/supernova-flutter-exporter. Do not edit by hand.",
  "// Change the value in Supernova, then run the exporter.",
  "// Supernova cannot run `dart format`, so the output opts out of it (Dart 3.7+).",
  "// dart format off",
  "// ignore_for_file: camel_case_types",
  "",
].join("\n")

function file(path: string, name: string, body: string): GeneratedFile {
  return { path, name, content: `${HEADER}${body.trimEnd()}\n` }
}

function relativeImport(fromDir: string, toPath: string): string {
  const up = fromDir.split("/").filter(Boolean).length
  return `${"../".repeat(up)}${toPath}`
}

const coreRef = (token: ModelToken) => `${coreClassFor(token)}.${dartMember(token.key)}`

// ---------------------------------------------------------------------------
// Reference resolution
// ---------------------------------------------------------------------------

/**
 * The Dart expression a semantic value compiles to.
 *
 * A `const` constructor cannot read another field of the same object, so a
 * semantic-to-semantic alias is followed, in the same brand and mode, until it
 * lands on a core token. A value with no alias, or a broken chain, falls back
 * to its literal and is reported.
 */
function expressionFor(
  token: ModelToken,
  brand: string,
  mode: Mode,
  byKey: Map<string, ModelToken>,
  notes: Set<string>,
): string {
  if (token.layer === "core") return coreRef(token)
  const visited = new Set<string>()
  let current = token
  for (;;) {
    const value = valueFor(current, brand, mode)
    if (!value.ref) {
      notes.add(`literal in semantic token: ${token.key}`)
      return dartLiteral(token, value.literal)
    }
    const target = byKey.get(value.ref)
    if (!target || visited.has(target.key)) {
      notes.add(`unresolved reference ${token.key} -> ${value.ref}; used literal`)
      return dartLiteral(token, value.literal)
    }
    if (target.layer === "core") return coreRef(target)
    visited.add(target.key)
    current = target
  }
}

/**
 * One gradient stop's colour: the same expression the colour token it reads
 * compiles to in this brand and mode, so `gradient.x.colors` equals the
 * matching `theme.skin…Stop` fields.
 */
function stopColorExpression(
  gradientKey: string,
  stop: GradientStop,
  brand: string,
  mode: Mode,
  byKey: Map<string, ModelToken>,
  notes: Set<string>,
): string {
  const target = stop.color.ref ? byKey.get(stop.color.ref) : undefined
  if (target?.kind === "color") return expressionFor(target, brand, mode, byKey, notes)
  notes.add(
    stop.color.ref
      ? `gradient ${gradientKey}: stop colour ${stop.color.ref} is not a colour token; used literal`
      : `gradient ${gradientKey}: stop colour is a literal`,
  )
  return dartColor(String(stop.color.literal))
}

function gradientExpression(
  token: ModelToken,
  brand: string,
  mode: Mode,
  byKey: Map<string, ModelToken>,
  notes: Set<string>,
): string {
  const gradient = gradientFor(token.gradient!, brand, mode)
  const { begin, end } = dartAlignments(gradient.angle)
  const colors = gradient.stops.map((stop) => stopColorExpression(token.key, stop, brand, mode, byKey, notes))
  const stops = gradient.stops.map((stop) => dartDouble(Number(stop.position.toFixed(4))))
  return `LinearGradient(begin: ${begin}, end: ${end}, colors: [${colors.join(", ")}], stops: [${stops.join(", ")}])`
}

