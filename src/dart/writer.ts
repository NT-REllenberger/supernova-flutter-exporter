function coreFile(className: string, name: string, doc: string, tokens: ModelToken[]): GeneratedFile {
  const needsUi = tokens.some((t) => dartTypeFor(t) === "Color")
  const needsAnimation = tokens.some((t) => dartTypeFor(t) === "Curve")
  const imports = [
    ...(needsUi ? ["import 'dart:ui';"] : []),
    ...(needsAnimation ? ["import 'package:flutter/animation.dart';"] : []),
  ]
  const body = [
    ...(imports.length > 0 ? [...imports, ""] : []),
    `/// ${doc}`,
    `abstract final class ${className} {`,
    ...tokens.map(
      (t) => `  static const ${dartTypeFor(t)} ${dartMember(t.key)} = ${dartLiteral(t, t.values.dark.literal)};`,
    ),
    "}",
  ].join("\n")
  return file("core/", name, body)
}

