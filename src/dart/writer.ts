const LERP: Partial<Record<DartType, string>> = {
  Color: "Color.lerp",
  double: "lerpDouble",
  TextStyle: "TextStyle.lerp",
  LinearGradient: "LinearGradient.lerp",
}

/** Types with no interpolation switch from one value to the other halfway. */
const SNAP: ReadonlySet<DartType> = new Set(["Duration", "Curve"])

function lerpExpression(type: DartType, member: string): string {
  if (SNAP.has(type)) return `t < 0.5 ? ${member} : other.${member}`
  const lerpCall = LERP[type]
  if (!lerpCall) throw new Error(`no lerp for ${type}`)
  return `${lerpCall}(${member}, other.${member}, t)!`
}

/** One field of a generated data class. */
interface Member {
  name: string
  type: DartType
  /** Doc comment lines, without the `///`. */
  doc?: string[]
}

function dataClass(className: string, doc: string, members: Member[], extra: string[] = []): string {
  const types = new Set(members.map((m) => m.type))
  // `values` stays a typed map when every field shares a type.
  const mapType = types.size === 1 ? [...types][0] : "Object"
  return [
    `/// ${doc}`,
    `final class ${className} {`,
    `  const ${className}({`,
    ...members.map((m) => `    required this.${m.name},`),
    "  });",
    "",
    ...members.flatMap((m) => [...(m.doc ?? []).map((line) => `  /// ${line}`), `  final ${m.type} ${m.name};`]),
    "",
    `  ${className} lerp(${className} other, double t) => ${className}(`,
    ...members.map((m) => `        ${m.name}: ${lerpExpression(m.type, m.name)},`),
    "      );",
    "",
    "  /// Every token by name, for swatches, debugging, and tests.",
    `  Map<String, ${mapType}> get values => {`,
    ...members.map((m) => `        '${m.name}': ${m.name},`),
    "      };",
    ...extra,
    "}",
  ].join("\n")
}

interface ThemeField {
  field: string
  className: string
  import: string
}

/** A brand-invariant semantic class with one `standard` instance. */
function standardFile(
  dir: string,
  name: string,
  className: string,
  doc: string,
  type: DartType,
  imports: string[],
  entries: Array<{ member: string; expr: string; type?: DartType }>,
  extra: string[] = [],
): GeneratedFile {
  const body = [
    ...imports,
    "",
    dataClass(
      className,
      doc,
      entries.map((e) => ({ name: e.member, type: e.type ?? type })),
      ["", "  /// The only set Strata defines today; every brand uses it.", `  static const standard = ${className}(`, ...entries.map((e) => `    ${e.member}: ${e.expr},`), "  );", ...extra],
    ),
  ].join("\n")
  return file(dir, name, body)
}

function typeStyleExpression(style: TypeStyle): string {
  const v = (value: Value, fallback: string) =>
    value.ref ? `${CORE_TYPOGRAPHY_CLASS}.${dartMember(value.ref)}` : fallback
  const num = (value: Value) => v(value, String(value.literal))
  const dbl = (value: Value) => v(value, Number.isInteger(Number(value.literal)) ? `${value.literal}.0` : `${value.literal}`)
  const family = v(style.family, `'${style.family.literal}'`)
  const size = dbl(style.size)
  const parts = [
    `package: '${DART_PACKAGE}'`,
    `fontFamily: ${family}`,
    `fontSize: ${size}`,
    `height: ${dbl(style.lineHeight)}`,
    "leadingDistribution: TextLeadingDistribution.even",
    `letterSpacing: ${dbl(style.tracking)} * ${size}`,
    `fontWeight: FontWeight(${num(style.weight)})`,
    `fontFeatures: [FontFeature('lnum', ${num(style.lnum)}), FontFeature('tnum', ${num(style.tnum)}), FontFeature('liga', ${num(style.liga)}), FontFeature('zero', ${num(style.zero)})]`,
    ...(style.underline ? ["decoration: TextDecoration.underline"] : []),
  ]
  return `TextStyle(${parts.join(", ")})`
}

const GRADIENT_DOC = [
  "Semantic gradients for one brand and mode, as web's `--gradient-*`.",
  "///",
  "/// Each stop reads a `theme.skin…Stop` colour, so the brand and mode come",
  "/// from the colours. The CSS angle becomes `begin` and `end` alignments",
  "/// that match web on a square box and at 0, 90, 180, and 270 degrees on",
  "/// any box. On a non-square box at any other angle, Flutter's gradient",
  "/// line follows the box's aspect ratio while CSS keeps the angle fixed, so",
  "/// a 156deg gradient runs flatter on a wide box than it does on web.",
].join("\n")

function themeFile(
  groups: Array<{ group: ColorGroup; members: string[] }>,
  gradients: ModelToken[],
  fields: ThemeField[],
): GeneratedFile {
  const classes = groups.map(({ group, members }) =>
    dataClass(
      group.className,
      `Semantic \`${group.prefix ?? "skin"}*\` colours for one brand and mode.`,
      members.map((name) => ({ name, type: "Color" as DartType })),
    ),
  )
  if (gradients.length > 0) {
    classes.push(
      dataClass(
        GRADIENT_CLASS,
        GRADIENT_DOC,
        gradients.map((t) => ({
          name: dartMember(t.key),
          type: "LinearGradient" as DartType,
          doc: [`CSS: \`${cssForGradient(t.gradient!.values.dark)}\``],
        })),
      ),
    )
  }
  const themeData = [
    "/// Every semantic token for one brand in one mode.",
    "///",
    "/// Brand files under `themes/brands/` define the instances. `StrataTheme`",
    "/// carries one down the widget tree.",
    `final class ${THEME_DATA_CLASS} {`,
    `  const ${THEME_DATA_CLASS}({`,
    "    required this.brightness,",
    ...fields.map((f) => `    required this.${f.field},`),
    "  });",
    "",
    "  final Brightness brightness;",
    ...fields.map((f) => `  final ${f.className} ${f.field};`),
    "",
    `  ${THEME_DATA_CLASS} lerp(${THEME_DATA_CLASS} other, double t) => ${THEME_DATA_CLASS}(`,
    "        brightness: t < 0.5 ? brightness : other.brightness,",
    ...fields.map((f) => `        ${f.field}: ${f.field}.lerp(other.${f.field}, t),`),
    "      );",
    "}",
  ].join("\n")
  const imports = [...new Set(fields.map((f) => f.import).filter(Boolean))].sort()
  const body = [
    "import 'dart:ui';",
    "",
    ...(gradients.length > 0 ? ["import 'package:flutter/painting.dart';", ""] : []),
    ...imports.map((i) => `import '${i}';`),
    "",
    ...classes.flatMap((c) => [c, ""]),
    themeData,
  ].join("\n")
  return file("semantics/", "theme.gen.dart", body)
}

function brandFile(
  brand: string,
  groups: Array<{ group: ColorGroup; tokens: ModelToken[] }>,
  gradients: ModelToken[],
  standards: ThemeField[],
  byKey: Map<string, ModelToken>,
  notes: Set<string>,
): GeneratedFile {
  const dir = "semantics/themes/brands/"
  const instance = (mode: Mode): string[] => [
    `  static const ${mode} = ${THEME_DATA_CLASS}(`,
    `    brightness: Brightness.${mode},`,
    ...groups.flatMap(({ group, tokens }) => [
      `    ${group.field}: ${group.className}(`,
      ...tokens.map((t) => `      ${dartMember(t.key)}: ${expressionFor(t, brand, mode, byKey, notes)},`),
      "    ),",
    ]),
    ...(gradients.length > 0
      ? [
          `    gradient: ${GRADIENT_CLASS}(`,
          ...gradients.map((t) => `      ${dartMember(t.key)}: ${gradientExpression(t, brand, mode, byKey, notes)},`),
          "    ),",
        ]
      : []),
    ...standards.map((s) => `    ${s.field}: ${s.className}.standard,`),
    "  );",
  ]
  const imports = [
    "core/color.gen.dart",
    "semantics/theme.gen.dart",
    ...standards.map((s) => `semantics/${s.import}`),
  ].map((p) => `import '${relativeImport(dir, p)}';`)
  const body = [
    "import 'dart:ui';",
    "",
    ...(gradients.length > 0 ? ["import 'package:flutter/painting.dart';", ""] : []),
    ...[...new Set(imports)].sort(),
    "",
    `/// The \`${brand}\` brand. Every value references a core token, so a ramp`,
    "/// change in Supernova reaches both modes through one constant.",
    `abstract final class ${brandClass(brand)} {`,
    ...instance("dark"),
    "",
    ...instance("light"),
    "}",
  ].join("\n")
  return file(dir, `${brand}.gen.dart`, body)
}

/** `enum StrataBrand` — the brands Supernova defines, each with both modes. */
function brandEnumFile(brands: string[]): GeneratedFile {
  const body = [
    "import 'dart:ui';",
    "",
    `import '../theme.gen.dart';`,
    ...brands.map((b) => `import 'brands/${b}.gen.dart';`),
    "",
    "/// Every Strata brand. Pick one per app flavor, then resolve a mode.",
    "enum StrataBrand {",
    ...brands.map((b, i) => `  ${b}(${brandClass(b)}.dark, ${brandClass(b)}.light)${i === brands.length - 1 ? ";" : ","}`),
    "",
    "  const StrataBrand(this.dark, this.light);",
    "",
    `  final ${THEME_DATA_CLASS} dark;`,
    `  final ${THEME_DATA_CLASS} light;`,
    "",
    "  /// The theme for [brightness], e.g. from `MediaQuery.platformBrightnessOf`.",
    `  ${THEME_DATA_CLASS} resolve(Brightness brightness) =>`,
    "      brightness == Brightness.dark ? dark : light;",
    "}",
  ].join("\n")
  return file("semantics/themes/", "brands.gen.dart", body)
}

