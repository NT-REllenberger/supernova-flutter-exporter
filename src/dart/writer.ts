/**
 * Dart writer: turns the token model into the `lib/src/tokens/` file set.
 *
 *   core/color.gen.dart                 TokenCore_Color       — the only colour literals
 *   core/density.gen.dart               TokenCore_Density     — radius, spacing, size literals
 *   core/typography.gen.dart            TokenCore_Typography  — typescale literals
 *   core/motion.gen.dart                TokenCore_Motion      — duration and easing literals
 *   semantics/density/radius.gen.dart   TokenSemanticDensity_Radius   (data class + `standard`)
 *   semantics/density/spacing.gen.dart  TokenSemanticDensity_Spacing
 *   semantics/density/size.gen.dart     TokenSemanticDensity_Size
 *   semantics/typography.gen.dart       TokenSemantic_Typography      (TextStyles + `standard`)
 *   semantics/motion.gen.dart           TokenSemantic_Motion          (Durations, Curves + `standard`)
 *   semantics/theme.gen.dart            colour and gradient group classes + StrataThemeData (shapes, lerp)
 *   semantics/themes/brands/<b>.gen.dart  dark + light StrataThemeData, references only
 *   semantics/themes/brands.gen.dart    enum StrataBrand
 *   tokens.gen.dart                     barrel
 *   manifest.gen.json                   key -> Dart symbol -> Supernova id, for the MCP
 *
 * Tokens import `dart:ui`. Typography and gradients also need
 * `package:flutter/painting.dart`, for `TextStyle` and `LinearGradient`.
 * Nothing imports Material, Cupertino, or the widgets layer.
 */

